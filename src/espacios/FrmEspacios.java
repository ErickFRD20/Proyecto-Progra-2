    @Override
    public void showData(Espacio data) {
        if (data == null) return;
        txtBuscar.setText(data.getNumero());
        cmbTipo.setSelectedItem(data.getTipo());
        txtTamano.setText(String.valueOf(data.getTamano()));
        txtPrecio.setText(String.valueOf(data.getPrecioMes()));
        txtEstado.setText(data.getEstado().getEstado());
    }

