    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed

        String actualizarNum = txtBuscar.getText();
        TipoEspacio tipo = (TipoEspacio) cmbTipo.getSelectedItem();
        
        if(actualizarNum.equals("")){
            showError("Ingrese el ID o numero de espacio a actualizar");
            return;
        }
        
        try{
            double tamano = Double.parseDouble(txtTamano.getText());
            double precio = Double.parseDouble(txtPrecio.getText());
            controller.actualizarEspacio(actualizarNum, precio, tamano, tipo);
        }catch (NumberFormatException e) {
            showError("El tamaño y el precio no son valores validos");
        }           
    }//GEN-LAST:event_btnActualizarActionPerformed

