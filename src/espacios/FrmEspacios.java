    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        String numero = txtBuscar.getText();
        String tamanoText = txtTamano.getText();
        String precioText = txtPrecio.getText();
        TipoEspacio tipo = (TipoEspacio) cmbTipo.getSelectedItem();
        
       if (numero.equals("") || tamanoText.equals("") || precioText.equals("")){
           showError("Digite la informacion de todos los datos");
           return;
        }
       
       try {
            double tamano = Double.parseDouble(tamanoText);
            double precio = Double.parseDouble(precioText);
            Espacio espacio = new Espacio(numero, precio, tamano, tipo);
            controller.agregarEspacio(espacio);
       
        }catch (NumberFormatException e) {
            showError("El tamaño y el precio deben ser valores validos");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

        String eliminarNum = txtBuscar.getText();
        
        if (eliminarNum.equals("")){
            showError("Ingrese el ID o numero de espacio a eliminar");
            return;
        }
        
        controller.eliminarEspacio(eliminarNum);
        clear();               
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed

        String numero = txtBuscar.getText();
        
        if (numero.equals("")){
            showError("Digite un ID o  numero de espacio a buscar");
            return;
        }
        
        Espacio espacioEncontrado = controller.buscarEspacio(numero);
        
        if (espacioEncontrado != null) showData(espacioEncontrado);
        
    }//GEN-LAST:event_btnBuscarActionPerformed

