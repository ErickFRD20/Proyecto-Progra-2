    private void listarServicios() {
        DefaultTableModel modelo;
        modelo=(DefaultTableModel) tblServicios.getModel();
        modelo.setRowCount(0);
        Iterator lista;
        lista = controlador.listarServicios();
        while (lista.hasNext()) {
            servicioExtra servicio;
            servicio = (servicioExtra) lista.next();
            modelo.addRow(new Object[]{
            servicio.getCodigo(),
            servicio.getNombre(),
            servicio.getDescripcion(),
            servicio.getPrecio()
                    
        });}}
    

    

