    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
         if (txtCodigo.getText().equals("")) {
        showError("escriba un codigo");
    } else if (txtNombre.getText().equals("")) {
        showError("tiene que poner un nombre");
    } else if (txtDescripcion.getText().equals("")) {
        showError("tiene que poner una descripcion");
    } else if (txtPrecio.getText().equals("")) {
        showError("tiene que ingresar un precio");
    } else {int codigo = Integer.parseInt(txtCodigo.getText());
        double precio = Double.parseDouble(txtPrecio.getText());
        controlador.agregarServicio(codigo,txtNombre.getText(),
                txtDescripcion.getText(),precio);
        listarServicios();}

    

    }//GEN-LAST:event_btnAgregarActionPerformed

